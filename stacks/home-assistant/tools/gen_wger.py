#!/usr/bin/env python3
"""Load the workout catalog into wger: custom exercises + one weekday-pinned routine per person.

    WGER_URL=https://wger.kmkdp.com WGER_API_KEY_JMACK=... WGER_API_KEY_RACH=... \\
    python3 stacks/home-assistant/tools/gen_wger.py --posters DIR            # dry run: print the plan
    python3 stacks/home-assistant/tools/gen_wger.py --posters DIR --apply    # write it
    python3 stacks/home-assistant/tools/gen_wger.py --posters DIR --check    # exit 1 on drift
    ... --person rach                                                        # one person only

Reads  tools/workout_catalog.json (people + the slugs; same loader as gen_workout.py)
       DIR/workout.json           (the guide output: days, steps, doses, titles, cues)
       DIR/exercise/ex-<slug>-rom.png (the posters)
Config from the environment only: WGER_URL, and one API key per person in
WGER_API_KEY_<LOGIN> (login upper-cased, e.g. WGER_API_KEY_JMACK). Keys never go in argv.

What it writes (runbook: docs/runbooks/wger.md, "Load the catalog"):
  1. One custom exercise per slug (catalog slugs + any slug the guide uses), English
     translation: name = catalog name (or the guide title for multi-slug items),
     description = title, doses per day, cues, and a marker line
     "kdk:<slug> v:<text hash> img:<poster hash>#<image id>". The marker is the
     idempotency key: exercises are found by it, the text is patched only when its
     hash changes, the poster is uploaded only when its hash changes (the old image
     is deleted). Exercises are global in wger, so they are written with the FIRST
     person's key (jmack, a wger superuser: trusted + exempt from the 20/hour
     exercise-create throttle) and only when that person is selected.
  2. Units: looked up by name (Repetitions, Seconds, Minutes, "10-ft lengths"; lb).
     The REST API cannot create units. A missing one is printed as an admin step and
     --apply then stops before the routines.
  3. Per person, the routine "Week (kdk)": fit_in_week, starts on a Monday, 7 days
     (order 1..7 = Monday..Sunday, none needs logs to advance, so day N is always
     weekday N), one slot per guide step in the guide's order, supersets as one slot
     with two entries, "Every day" steps expanded, sets/reps/max-reps from the dose
     text, weights left blank. wger caps a routine at 120 days, so the window is 17
     weeks and an --apply within 28 days of the end rolls it forward to this week.
Slots are matched by their exercises, never rebuilt: a WorkoutLog cascades away with
its slot entry, so a slot that has logs is never deleted (it is moved to the end and
marked "[retired]" instead), and days and the routine are never deleted.
"""
