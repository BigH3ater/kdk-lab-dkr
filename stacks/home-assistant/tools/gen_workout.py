#!/usr/bin/env python3
"""Generate the Workout helpers + dashboards for every person from ONE exercise list.

    python3 stacks/home-assistant/tools/gen_workout.py           # rewrite the 4 files
    python3 stacks/home-assistant/tools/gen_workout.py --check   # exit 1 if they are stale

Reads  tools/workout_catalog.json        (people, groups, exercises + kind)
       tools/workout_dashboard_head.yaml (dashboard header + shared Treadmill view)
Writes config/packages/workout_strength.yaml  + workout_strength_<person>.yaml
       config/dashboards/workout.yaml          + workout_<person>.yaml

Never hand-edit the generated files: change the catalog (or this script) and re-run.
The runbook is docs/runbooks/workout-tracking-update.md.

Kinds (what gets logged for one exercise):
  w      weight (lb) + reps          ex_<id>_weight, ex_<id>_reps
  r      reps only (body weight)     ex_<id>_reps
  t      seconds only (holds)        ex_<id>_seconds
  wt     weight + seconds (holds)    ex_<id>_weight, ex_<id>_seconds
  wl     weight + 10-ft lengths      ex_<id>_weight, ex_<id>_lengths   (carries)
  min    minutes                     ex_<id>_minutes
  score  0-10 rating                 ex_<id>_score
  done   "done at" timestamp         input_datetime.ex_<id>_done
Every entity id gets the person's suffix ("" for the first person, "_rachel" ...).
The same list feeds the home.kmkdp.com /workout/ log page (stacks/dashboard/workout).

Stdlib only.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
HA = TOOLS.parent
CATALOG = TOOLS / "workout_catalog.json"
HEAD = TOOLS / "workout_dashboard_head.yaml"

FIELDS = {
    "w": ["weight", "reps"],
    "r": ["reps"],
    "t": ["seconds"],
    "wt": ["weight", "seconds"],
    "wl": ["weight", "lengths"],
    "min": ["minutes"],
    "score": ["score"],
    "done": ["done"],
}
# input_number settings per field: (label, min, max, step, unit, icon)
NUMBER = {
    "weight": ("weight", 0, 200, 0.5, "lb", "mdi:weight-pound"),
    "reps": ("reps", 0, 50, 1, None, "mdi:counter"),
    "seconds": ("seconds", 0, 600, 1, "s", "mdi:timer-outline"),
    "lengths": ("lengths", 0, 20, 1, None, "mdi:map-marker-distance"),
    "minutes": ("minutes", 0, 240, 1, "min", "mdi:timer"),
    "score": ("score", 0, 10, 1, None, "mdi:numeric"),
}
ROW_NAME = {"weight": "Weight (lb)", "reps": "Reps", "seconds": "Seconds", "lengths": "Lengths (10 ft)",
            "minutes": "Minutes", "score": "Score (0-10)", "done": "Last done"}
PROGRESS_FIELD = ["weight", "seconds", "lengths", "reps", "minutes", "score"]  # first match is graphed

PACKAGE_HEAD = """\
# Strength log — per-exercise weight (lb) + reps for the dumbbell/bench program.
# Generic exercise names + Lower/Upper day grouping only; no health details or
# prescribed loads (those live in the host-managed guide). You update these each
# session; HA's recorder keeps the history, so the Strength dashboard's graphs show
# progression over time. Entity ids: input_number.ex_<name>_weight / _reps.
"""
GENERATED = ("# GENERATED by stacks/home-assistant/tools/gen_workout.py from "
             "tools/workout_catalog.json -- do not hand-edit.\n")


def fields(item: dict) -> list[str]:
    return FIELDS[item["kind"]]


def entity(item: dict, field: str, suffix: str) -> str:
    domain = "input_datetime" if field == "done" else "input_number"
    return f"{domain}.ex_{item['id']}_{field}{suffix}"


def load() -> dict:
    cat = json.loads(CATALOG.read_text(encoding="utf-8"))
    groups = {g["key"] for g in cat["groups"]}
    ids = set()
    for it in cat["items"]:
        assert it["kind"] in FIELDS, f"unknown kind {it['kind']!r} for {it['id']}"
        assert it["group"] in groups, f"unknown group {it['group']!r} for {it['id']}"
        assert it["id"] not in ids, f"duplicate id {it['id']}"
        assert it["id"].replace("_", "").isalnum() and it["id"].islower(), f"bad id {it['id']}"
        ids.add(it["id"])
    return cat


def items_by_group(cat: dict):
    for g in cat["groups"]:
        its = [it for it in cat["items"] if it["group"] == g["key"]]
        if its:
            yield g, its


# ---------------------------------------------------------------- package
def package(cat: dict, person: dict) -> str:
    sfx = person["suffix"]
    out = [line + "\n" for line in person.get("package_intro", [])]
    out.append(cat.get("package_head", PACKAGE_HEAD))
    if cat.get("generated_banner", False):
        out.append(GENERATED)
    out.append("input_number:\n")
    dt = []
    for g, its in items_by_group(cat):
        out.append(f"  # --- {g['comment']} ---\n")
        for it in its:
            for f in fields(it):
                if f == "done":
                    dt.append((g, it))
                    continue
                label, lo, hi, step, unit, icon = NUMBER[f]
                out.append(f"  ex_{it['id']}_{f}{sfx}:\n")
                out.append(f"    name: {it['name']} {label}\n")
                out.append(f"    min: {lo}\n    max: {hi}\n    step: {step}\n")
                if unit:
                    out.append(f"    unit_of_measurement: {unit}\n")
                out.append(f"    mode: box\n    icon: {icon}\n")
    if dt:
        out.append("input_datetime:\n")
        for g, it in dt:
            out.append(f"  ex_{it['id']}_done{sfx}:\n")
            out.append(f"    name: {it['name']} done\n")
            out.append("    has_date: true\n    has_time: true\n    icon: mdi:check-circle-outline\n")
    if person.get("owns_scripts") and dt:
        out.append(MARK_DONE_SCRIPT)
    return "".join(out)


MARK_DONE_SCRIPT = """\
# Shared by every person's dashboard ("Mark done now" rows). Defined once, here.
script:
  workout_mark_done:
    alias: Workout - mark done now
    icon: mdi:check-bold
    mode: queued
    fields:
      target_entity:
        description: The input_datetime.ex_*_done helper to stamp with the current time.
        example: input_datetime.ex_stretches_done
        required: true
        selector:
          entity:
            domain: input_datetime
    sequence:
    - action: input_datetime.set_datetime
      target:
        entity_id: "{{ target_entity }}"
      data:
        timestamp: "{{ now().timestamp() }}"
"""


# ---------------------------------------------------------------- dashboard
def dashboard(cat: dict, person: dict) -> str:
    sfx = person["suffix"]
    head = HEAD.read_text(encoding="utf-8").splitlines(keepends=True)[3:]
    out = ["".join(head).replace("__TITLE__", person["title"])]
    out.append("- title: Strength\n  path: strength\n  icon: mdi:dumbbell\n  type: masonry\n  cards:\n")
    out.append("  - type: markdown\n    content: >-\n")
    for line in cat["strength_intro"]:
        out.append(f"      {line}\n")
    for g, its in items_by_group(cat):
        out.append(f"  - type: entities\n    title: {g['title']}\n"
                   "    show_header_toggle: false\n    state_color: false\n    entities:\n")
        for it in its:
            out.append(f"    - type: section\n      label: {it['name']}\n")
            for f in fields(it):
                out.append(f"    - entity: {entity(it, f, sfx)}\n      name: {ROW_NAME[f]}\n")
                if f == "done":
                    out.append("      icon: mdi:check-circle-outline\n")
                    out.append("    - type: button\n      name: Mark done now\n      icon: mdi:check-bold\n"
                               "      action_name: Done\n      tap_action:\n        action: perform-action\n"
                               "        perform_action: script.workout_mark_done\n        data:\n"
                               f"          target_entity: {entity(it, f, sfx)}\n")
                else:
                    out.append(f"      icon: {NUMBER[f][5]}\n")
    out.append("\n- title: Progress\n  path: progress\n  icon: mdi:chart-line\n  type: masonry\n  cards:\n")
    for g, its in items_by_group(cat):
        rows = []
        for it in its:
            f = next((x for x in PROGRESS_FIELD if x in fields(it)), None)
            if f:
                rows.append(f"    - entity: {entity(it, f, sfx)}\n      name: {it['name']}\n")
        if rows:
            out.append(f"  - type: history-graph\n    title: {g['title']}\n    hours_to_show: 2160\n    entities:\n")
            out.extend(rows)
    out.append(PLAN_VIEW)
    return "".join(out)


PLAN_VIEW = """
- title: Plan
  path: plan
  icon: mdi:clipboard-text
  type: panel
  cards:
  - type: iframe
    url: https://home.kmkdp.com/guides/workout/workout.html
    aspect_ratio: 150%
"""


def outputs(cat: dict) -> dict[Path, str]:
    res = {}
    for p in cat["people"]:
        pk = "" if not p["suffix"] else p["suffix"]
        res[HA / "config" / "packages" / f"workout_strength{pk}.yaml"] = package(cat, p)
        res[HA / "config" / "dashboards" / f"workout{pk}.yaml"] = dashboard(cat, p)
    return res


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if a generated file is out of date")
    args = ap.parse_args()
    cat = load()
    stale = []
    for path, text in outputs(cat).items():
        cur = path.read_text(encoding="utf-8") if path.exists() else None
        if cur == text:
            continue
        if args.check:
            stale.append(path)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(HA.parent.parent)}")
    if stale:
        for p in stale:
            print(f"STALE: {p.relative_to(HA.parent.parent)} -- run tools/gen_workout.py", file=sys.stderr)
        return 1
    if args.check:
        print("workout files up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
